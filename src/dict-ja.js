// GitHub の画面の英語 → 日本語の辞書
//
// ■ exact（完全一致）
//   画面の文字（前後の空白を除いたもの）が、キーとぴったり同じときだけ置き換える。
//   ユーザーが書いた文（コミットメッセージ・イシューの題名など）を間違って訳さないため。
//
// ■ 値の書き方
//   'そのまま日本語'
//   '[[pr]]'                   → 「プルリクエスト (Pull request)」＋ホバー説明（terms.js の pr）
//   '[[pr|Pull requests]]'     → 「プルリクエスト (Pull requests)」（括弧の中の英語を指定）
//   '新しい[[pr]]'             → 前後に文を付けてもよい
//
// ■ patterns（正規表現）
//   数字入りの文など。[正規表現, 置き換え] の組。置き換えの中で $1 などが使える。
//
// 足したい・直したい文言があれば、GitHub のイシューかプルリクエストで送ってください。
// 時間の英語を日本語に（patterns から使う）
globalThis.GHJA_TIME = function (t) {
	const U = { second: '秒', minute: '分', hour: '時間', day: '日', week: '週間', month: 'か月', year: '年' };
	let m;
	if ((m = /^(\d+) (second|minute|hour|day|week|month|year)s? ago$/.exec(t))) return m[1] + ' ' + U[m[2]] + '前';
	if (t === 'yesterday') return '昨日';
	if ((m = /^last (week|month|year)$/.exec(t))) return { week: '先週', month: '先月', year: '昨年' }[m[1]];
	return t + ' ';
};

